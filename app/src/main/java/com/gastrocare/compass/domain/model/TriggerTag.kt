/** Интенсивность фактора риска в конкретном продукте (0 — нет, 1 — выражено, 2 — ярко). */
enum class TriggerIntensity(val factor: Double) {
    NONE(0.0),
    MILD(0.6),
    MODERATE(1.0),
    STRONG(1.6)
}

/**
 * Оценка одного фактора в продукте.
 * Гибридный подход: тег + интенсивность + при желании явная количественная метрика.
 */
data class TriggerFactor(
    val tag: TriggerTag,
    val intensity: TriggerIntensity = TriggerIntensity.MODERATE,
    /** Пояснение именно для этого продукта (может быть null — тогда берётся mechanism тега). */
    val note: String? = null
)
